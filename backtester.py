from typing import Dict, Any, List, Optional
import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.dates as mdates


class BacktestEngine:

    def __init__(
        self,
        initial_capital: float = 100000.0,
        commission_rate: float = 0.001,
        slippage_rate: float = 0.0005,
        risk_free_rate: float = 0.06,
    ):
        if initial_capital <= 0:
            raise ValueError("Initial capital must be strictly positive.")
        self.initial_capital = float(initial_capital)
        self.commission_rate = float(commission_rate)
        self.slippage_rate = float(slippage_rate)
        self.risk_free_rate = float(risk_free_rate)

        self.equity_curve: Optional[pd.DataFrame] = None
        self.trades: List[Dict[str, Any]] = []
        self.metrics: Dict[str, Any] = {}

    def run(self, df_with_signals: pd.DataFrame, ticker: str = "STOCK") -> pd.DataFrame:
        df = df_with_signals.copy()

        if "Signal" not in df.columns or "Position" not in df.columns:
            raise ValueError(
                "Input DataFrame must contain 'Position' and 'Signal' columns generated by strategy.py"
            )

        n = len(df)
        if n == 0:
            raise ValueError("Cannot run backtest on empty dataset.")

        cash = self.initial_capital
        shares = 0
        portfolio_values = []
        cash_history = []
        shares_history = []
        holdings_values = []
        self.trades = []

        current_trade: Optional[Dict[str, Any]] = None

        first_close = float(df["Close"].iloc[0])
        benchmark_shares = int(self.initial_capital // (first_close * (1 + self.commission_rate)))
        benchmark_initial_cost = benchmark_shares * first_close * (1 + self.commission_rate)
        benchmark_cash_rem = self.initial_capital - benchmark_initial_cost
        benchmark_values = []

        dates = df.index

        for i in range(n):
            date = dates[i]
            close_price = float(df["Close"].iloc[i])
            signal = int(df["Signal"].iloc[i])

            if signal == 1 and shares == 0:
                effective_buy_price = close_price * (1 + self.slippage_rate)
                cost_per_share = effective_buy_price * (1 + self.commission_rate)
                shares_to_buy = int(cash // cost_per_share)

                if shares_to_buy > 0:
                    trade_gross_val = shares_to_buy * effective_buy_price
                    commission_paid = trade_gross_val * self.commission_rate
                    total_outlay = trade_gross_val + commission_paid

                    cash -= total_outlay
                    shares = shares_to_buy

                    current_trade = {
                        "entry_date": date.strftime("%Y-%m-%d"),
                        "entry_price": round(effective_buy_price, 2),
                        "shares": shares_to_buy,
                        "capital_invested": round(total_outlay, 2),
                        "buy_commission": round(commission_paid, 2),
                        "entry_bar": i,
                    }

            elif signal == -1 and shares > 0:
                effective_sell_price = close_price * (1 - self.slippage_rate)
                trade_gross_val = shares * effective_sell_price
                commission_paid = trade_gross_val * self.commission_rate
                net_proceeds = trade_gross_val - commission_paid

                cash += net_proceeds

                if current_trade is not None:
                    holding_period = i - current_trade["entry_bar"]
                    total_commissions = current_trade["buy_commission"] + commission_paid
                    net_pnl = net_proceeds - current_trade["capital_invested"]
                    return_pct = (net_pnl / current_trade["capital_invested"]) * 100

                    trade_record = {
                        "trade_num": len(self.trades) + 1,
                        "entry_date": current_trade["entry_date"],
                        "exit_date": date.strftime("%Y-%m-%d"),
                        "shares": shares,
                        "entry_price": current_trade["entry_price"],
                        "exit_price": round(effective_sell_price, 2),
                        "invested_capital": current_trade["capital_invested"],
                        "net_proceeds": round(net_proceeds, 2),
                        "net_pnl": round(net_pnl, 2),
                        "return_pct": round(return_pct, 2),
                        "commissions": round(total_commissions, 2),
                        "holding_days": holding_period,
                        "outcome": "WIN" if net_pnl > 0 else "LOSS",
                    }
                    self.trades.append(trade_record)
                    current_trade = None

                shares = 0

            holdings_val = shares * close_price
            total_equity = cash + holdings_val
            bench_val = benchmark_cash_rem + (benchmark_shares * close_price)

            shares_history.append(shares)
            cash_history.append(cash)
            holdings_values.append(holdings_val)
            portfolio_values.append(total_equity)
            benchmark_values.append(bench_val)

        if current_trade is not None and shares > 0:
            final_close = float(df["Close"].iloc[-1])
            final_gross = shares * final_close
            est_comm = final_gross * self.commission_rate
            net_proceeds = final_gross - est_comm
            net_pnl = net_proceeds - current_trade["capital_invested"]
            return_pct = (net_pnl / current_trade["capital_invested"]) * 100

            trade_record = {
                "trade_num": len(self.trades) + 1,
                "entry_date": current_trade["entry_date"],
                "exit_date": dates[-1].strftime("%Y-%m-%d") + " (Open)",
                "shares": shares,
                "entry_price": current_trade["entry_price"],
                "exit_price": round(final_close, 2),
                "invested_capital": current_trade["capital_invested"],
                "net_proceeds": round(net_proceeds, 2),
                "net_pnl": round(net_pnl, 2),
                "return_pct": round(return_pct, 2),
                "commissions": round(current_trade["buy_commission"] + est_comm, 2),
                "holding_days": n - 1 - current_trade["entry_bar"],
                "outcome": "OPEN",
            }
            self.trades.append(trade_record)

        df["Shares"] = shares_history
        df["Cash"] = cash_history
        df["Holdings_Value"] = holdings_values
        df["Total_Value"] = portfolio_values
        df["Benchmark_Value"] = benchmark_values

        df["Daily_Return"] = df["Total_Value"].pct_change().fillna(0.0)
        df["Peak_Value"] = df["Total_Value"].cummax()
        df["Drawdown_Pct"] = ((df["Total_Value"] - df["Peak_Value"]) / df["Peak_Value"]) * 100

        df["Benchmark_Daily_Return"] = df["Benchmark_Value"].pct_change().fillna(0.0)
        df["Benchmark_Peak"] = df["Benchmark_Value"].cummax()
        df["Benchmark_Drawdown_Pct"] = (
            (df["Benchmark_Value"] - df["Benchmark_Peak"]) / df["Benchmark_Peak"]
        ) * 100

        self.equity_curve = df
        self.metrics = self._calculate_metrics(df, ticker)
        return df

    def _calculate_metrics(self, df: pd.DataFrame, ticker: str) -> Dict[str, Any]:
        final_val = float(df["Total_Value"].iloc[-1])
        initial_val = self.initial_capital
        total_pnl = final_val - initial_val
        total_return_pct = (total_pnl / initial_val) * 100

        final_bench = float(df["Benchmark_Value"].iloc[-1])
        bench_return_pct = ((final_bench - initial_val) / initial_val) * 100

        alpha_pct = total_return_pct - bench_return_pct

        days_span = (df.index[-1] - df.index[0]).days
        years_span = max(days_span / 365.25, 0.05)

        if final_val > 0:
            cagr = ((final_val / initial_val) ** (1 / years_span) - 1) * 100
        else:
            cagr = -100.0

        if final_bench > 0:
            bench_cagr = ((final_bench / initial_val) ** (1 / years_span) - 1) * 100
        else:
            bench_cagr = -100.0

        max_drawdown_pct = float(df["Drawdown_Pct"].min())
        bench_max_dd_pct = float(df["Benchmark_Drawdown_Pct"].min())

        daily_returns = df["Daily_Return"]
        trading_days_per_year = 252
        annualized_volatility = float(daily_returns.std() * np.sqrt(trading_days_per_year)) * 100

        daily_rf = (1 + self.risk_free_rate) ** (1 / trading_days_per_year) - 1
        excess_returns = daily_returns - daily_rf
        excess_std = excess_returns.std()

        if excess_std > 0:
            sharpe_ratio = float((excess_returns.mean() / excess_std) * np.sqrt(trading_days_per_year))
        else:
            sharpe_ratio = 0.0

        downside_returns = daily_returns[daily_returns < daily_rf]
        if len(downside_returns) > 0 and downside_returns.std() > 0:
            sortino_ratio = float(
                (excess_returns.mean() / (downside_returns.std())) * np.sqrt(trading_days_per_year)
            )
        else:
            sortino_ratio = 0.0

        closed_trades = [t for t in self.trades if t.get("outcome") in ["WIN", "LOSS"]]
        total_closed_trades = len(closed_trades)
        winning_trades = [t for t in closed_trades if t["outcome"] == "WIN"]
        losing_trades = [t for t in closed_trades if t["outcome"] == "LOSS"]

        win_count = len(winning_trades)
        loss_count = len(losing_trades)
        win_rate_pct = (win_count / total_closed_trades * 100) if total_closed_trades > 0 else 0.0

        gross_profits = sum(t["net_pnl"] for t in winning_trades)
        gross_losses = abs(sum(t["net_pnl"] for t in losing_trades))

        if gross_losses > 0:
            profit_factor = round(gross_profits / gross_losses, 2)
        elif gross_profits > 0:
            profit_factor = float("inf")
        else:
            profit_factor = 0.0

        trade_returns = [t["return_pct"] for t in closed_trades]
        avg_trade_return = float(np.mean(trade_returns)) if trade_returns else 0.0
        best_trade = float(np.max(trade_returns)) if trade_returns else 0.0
        worst_trade = float(np.min(trade_returns)) if trade_returns else 0.0

        market_exposure_pct = float((df["Shares"] > 0).mean() * 100)

        return {
            "Ticker": ticker,
            "Initial Capital (Rs.)": round(initial_val, 2),
            "Final Capital (Rs.)": round(final_val, 2),
            "Net Profit (Rs.)": round(total_pnl, 2),
            "Strategy Total Return (%)": round(total_return_pct, 2),
            "Benchmark Return (%)": round(bench_return_pct, 2),
            "Alpha vs Benchmark (%)": round(alpha_pct, 2),
            "Strategy CAGR (%)": round(cagr, 2),
            "Benchmark CAGR (%)": round(bench_cagr, 2),
            "Strategy Max Drawdown (%)": round(max_drawdown_pct, 2),
            "Benchmark Max Drawdown (%)": round(bench_max_dd_pct, 2),
            "Annualized Volatility (%)": round(annualized_volatility, 2),
            "Sharpe Ratio": round(sharpe_ratio, 2),
            "Sortino Ratio": round(sortino_ratio, 2),
            "Total Closed Trades": total_closed_trades,
            "Winning Trades": win_count,
            "Losing Trades": loss_count,
            "Win Rate (%)": round(win_rate_pct, 2),
            "Profit Factor": profit_factor,
            "Avg Trade Return (%)": round(avg_trade_return, 2),
            "Best Trade (%)": round(best_trade, 2),
            "Worst Trade (%)": round(worst_trade, 2),
            "Market Exposure (%)": round(market_exposure_pct, 2),
        }

    def get_trades_df(self) -> pd.DataFrame:
        if not self.trades:
            return pd.DataFrame()
        return pd.DataFrame(self.trades)

    def plot_results(
        self,
        ticker: str = "STOCK",
        save_path: Optional[str] = None,
        show: bool = False,
    ) -> str:
        if self.equity_curve is None:
            raise RuntimeError("Must call run() before plotting.")

        df = self.equity_curve
        metrics = self.metrics

        plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")
        fig, axes = plt.subplots(3, 1, figsize=(14, 11), sharex=True, gridspec_kw={"height_ratios": [2.5, 2, 1.2]})
        fig.suptitle(
            f"Quantitative Backtest Performance: {ticker}\n"
            f"Strategy Total Return: {metrics.get('Strategy Total Return (%)', 0)}%  |  "
            f"Benchmark (Buy & Hold): {metrics.get('Benchmark Return (%)', 0)}%  |  "
            f"Sharpe Ratio: {metrics.get('Sharpe Ratio', 0)}",
            fontsize=14,
            fontweight="bold",
            y=0.98,
        )

        ax1 = axes[0]
        ax1.plot(df.index, df["Close"], label=f"{ticker} Close Price", color="#1f77b4", linewidth=1.3, alpha=0.9)

        for col in df.columns:
            if col.startswith("SMA_") and not col.endswith("Dist_Pct"):
                ax1.plot(df.index, df[col], label=col, linewidth=1.2, linestyle="--")

        buy_points = df[df["Signal"] == 1]
        sell_points = df[df["Signal"] == -1]

        ax1.scatter(
            buy_points.index,
            buy_points["Close"],
            marker="^",
            color="#2ca02c",
            s=90,
            label="BUY Trigger",
            zorder=5,
        )
        ax1.scatter(
            sell_points.index,
            sell_points["Close"],
            marker="v",
            color="#d62728",
            s=90,
            label="SELL Trigger",
            zorder=5,
        )

        ax1.set_ylabel("Price (Rs.)", fontsize=11, fontweight="bold")
        ax1.legend(loc="upper left", frameon=True)
        ax1.set_title("Market Price Action & Strategy Signals", fontsize=11, loc="left", fontweight="bold")

        ax2 = axes[1]
        ax2.plot(
            df.index,
            df["Total_Value"],
            label=f"Strategy Equity (Final: Rs. {metrics.get('Final Capital (Rs.)', 0):,.0f})",
            color="#2ca02c",
            linewidth=1.8,
        )
        ax2.plot(
            df.index,
            df["Benchmark_Value"],
            label=f"Buy & Hold Benchmark (Final: Rs. {df['Benchmark_Value'].iloc[-1]:,.0f})",
            color="#7f7f7f",
            linewidth=1.2,
            linestyle=":",
        )
        ax2.axhline(self.initial_capital, color="#000000", linestyle="--", linewidth=0.8, alpha=0.7, label="Initial Capital")
        ax2.set_ylabel("Portfolio Value (Rs.)", fontsize=11, fontweight="bold")
        ax2.legend(loc="upper left", frameon=True)
        ax2.set_title("Equity Curve vs Buy & Hold Benchmark", fontsize=11, loc="left", fontweight="bold")

        ax3 = axes[2]
        ax3.fill_between(df.index, df["Drawdown_Pct"], 0, color="#d62728", alpha=0.35, label=f"Strategy Drawdown (Max: {metrics.get('Strategy Max Drawdown (%)', 0)}%)")
        ax3.plot(df.index, df["Benchmark_Drawdown_Pct"], color="#7f7f7f", linewidth=0.8, linestyle=":", label=f"Benchmark Drawdown (Max: {metrics.get('Benchmark Max Drawdown (%)', 0)}%)")
        ax3.set_ylabel("Drawdown (%)", fontsize=11, fontweight="bold")
        ax3.set_xlabel("Date", fontsize=11, fontweight="bold")
        ax3.legend(loc="lower left", frameon=True)
        ax3.set_title("Underwater Equity & Drawdown Risk Profile", fontsize=11, loc="left", fontweight="bold")

        for ax in axes:
            ax.xaxis.set_major_formatter(mdates.DateFormatter("%b %Y"))
            ax.grid(True, linestyle="--", alpha=0.5)

        plt.tight_layout(rect=[0, 0.03, 1, 0.95])

        if not save_path:
            save_path = f"backtest_{ticker.replace('^', '').replace('.NS', '')}.png"

        out_dir = os.path.dirname(save_path)
        if out_dir:
            os.makedirs(out_dir, exist_ok=True)

        fig.savefig(save_path, dpi=200, bbox_inches="tight")
        if show:
            plt.show()
        plt.close(fig)

        return save_path


